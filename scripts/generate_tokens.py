"""Generate the Compose design tokens from design/tokens.json.

design/tokens.json is a copy of the Azkarify design system's tokens, shared with iOS.
Run this script after updating it; the output is checked in.
"""
import json
import re
from pathlib import Path

repo = Path(__file__).resolve().parents[1]
tokens = json.loads((repo / 'design/tokens.json').read_text())
out = repo / 'app/src/main/java/sh/saeed/azkarify/ui/theme/AzTokens.kt'


def camel(name):
    head, *rest = name.split('-')
    return head + ''.join(part[:1].upper() + part[1:] for part in rest)


def color(value):
    value = value.lstrip('#')
    if len(value) == 3:
        value = ''.join(c * 2 for c in value)
    return f'Color(0xFF{value.upper()})'


def px(value):
    number = float(value.removesuffix('px'))
    return f'{number:g}'


def em(value):
    return f'{float(value.removesuffix("em")):g}'


colors = tokens['color']['tokens']
accents = [c for c in colors if c['name'].startswith('accent-')]
roles = [c for c in colors if not c['name'].startswith('accent-')]


def theme_value(token, theme):
    value = token['value']
    return value[theme] if isinstance(value, dict) else value


lines = [
    '// Generated by scripts/generate_tokens.py from design/tokens.json. Do not edit.',
    '',
    'package sh.saeed.azkarify.ui.theme',
    '',
    'import androidx.compose.runtime.Immutable',
    'import androidx.compose.ui.graphics.Color',
    'import androidx.compose.ui.text.TextStyle',
    'import androidx.compose.ui.text.font.FontFamily',
    'import androidx.compose.ui.text.font.FontWeight',
    'import androidx.compose.ui.text.style.LineHeightStyle',
    'import androidx.compose.ui.unit.DpOffset',
    'import androidx.compose.ui.unit.dp',
    'import androidx.compose.ui.unit.em',
    'import androidx.compose.ui.unit.sp',
    '',
    '/** Colour roles. `accent` and `onAccent` hold the chosen [AzAccent]. */',
    '@Immutable',
    'data class AzColors(',
]
lines += [f'    val {camel(c["name"])}: Color,' for c in roles]
lines += ['    val isDark: Boolean,', ')', '']
for theme, name in [('light', 'AzDayColors'), ('dark', 'AzNightColors')]:
    lines.append(f'val {name} =')
    lines.append('    AzColors(')
    lines += [f'        {camel(c["name"])} = {color(theme_value(c, theme))},' for c in roles]
    lines.append(f'        isDark = {"true" if theme == "dark" else "false"},')
    lines.append('    )')
    lines.append('')

lines += [
    '/** Accent choices. [id] is the stored preference value, unchanged from earlier releases. */',
    'enum class AzAccent(val id: String, val day: Color, val night: Color) {',
]
for accent in accents:
    match = re.search(r'stored id "([a-z]+)"', accent['usage'])
    label = camel(accent['name'].removeprefix('accent-'))
    label = label[:1].upper() + label[1:]
    lines.append(
        f'    {label}("{match.group(1)}", {color(accent["value"]["light"])}, '
        f'{color(accent["value"]["dark"])}),'
    )
lines[-1] = lines[-1].removesuffix(',') + ';'
lines += [
    '',
    '    companion object {',
    '        fun of(id: String) = entries.firstOrNull { it.id == id } ?: Terracotta',
    '    }',
    '}',
    '',
]


def dp_object(name, family, prefix):
    result = [f'object {name} {{']
    for token in tokens[family]['tokens']:
        result.append(f'    val {camel(token["name"].removeprefix(prefix))} = {px(token["value"])}.dp')
    return result + ['}', '']


lines += dp_object('AzSpace', 'spacing', 'space-')
lines += dp_object('AzRadius', 'radius', 'radius-')
lines += dp_object('AzBorder', 'border', 'border-')

lines.append('/** Hard offset shadows. Mirror x in right-to-left layouts. */')
lines.append('object AzStamp {')
for token in tokens['shadow']['tokens']:
    x, y = token['value']['light'].split()[:2]
    lines.append(f'    val {camel(token["name"].removeprefix("stamp-"))} = DpOffset({px(x)}.dp, {px(y)}.dp)')
lines += ['}', '']

lines.append('/** Durations in milliseconds; every transition uses [AzEasing]. */')
lines.append('object AzDuration {')
for token in tokens['duration']['tokens']:
    lines.append(
        f'    const val {camel(token["name"].removeprefix("duration-"))} = '
        f'{token["value"].removesuffix("ms")}'
    )
lines += ['}', '']

lines += [
    '/** Type styles for one UI script. Latin and Arabic UI have their own sets. */',
    '@Immutable',
    'data class AzTypography(',
]
groups = {g['family']: {s['name'].removeprefix('ar-'): s for s in g['styles']} for g in tokens['type']['groups']}
latin, arabic = groups['latin'], groups['arabic']
names = list(dict.fromkeys(list(latin) + list(arabic)))
lines += [f'    val {camel(n)}: TextStyle,' for n in names]
lines += ['    /** Latin styles track and uppercase eyebrows; Arabic styles never do. */', '    val latin: Boolean,', ')', '']

lines += [
    'private val azLineHeight =',
    '    LineHeightStyle(LineHeightStyle.Alignment.Center, LineHeightStyle.Trim.None)',
    '',
    'private fun style(family: FontFamily, size: Float, line: Float, weight: Int, tracking: Float, tabular: Boolean = false) =',
    '    TextStyle(',
    '        fontFamily = family,',
    '        fontSize = size.sp,',
    '        lineHeight = line.sp,',
    '        fontWeight = FontWeight(weight),',
    '        letterSpacing = tracking.em,',
    '        lineHeightStyle = azLineHeight,',
    '        fontFeatureSettings = if (tabular) "tnum" else null,',
    '    )',
    '',
]


def style_call(style, family):
    tabular = ', tabular = true' if style['name'].endswith('numeral') else ''
    return (
        f'style({family}, {px(style["fontSize"])}f, {px(style["lineHeight"])}f, '
        f'{style["fontWeight"]}, {em(style["letterSpacing"])}f{tabular})'
    )


for fn, own, other, own_family, latin_flag in [
    ('azLatinTypography', latin, arabic, 'latin', 'true'),
    ('azArabicTypography', arabic, latin, 'arabic', 'false'),
]:
    lines.append(f'fun {fn}(latin: FontFamily, arabic: FontFamily) =')
    lines.append('    AzTypography(')
    for n in names:
        # A style one script lacks comes from the other: the zikr's Arabic is always Alan Sans.
        if n in own:
            lines.append(f'        {camel(n)} = {style_call(own[n], own_family)},')
        else:
            family = 'arabic' if n.startswith('reading-arabic') else 'latin'
            lines.append(f'        {camel(n)} = {style_call(other[n], family)},')
    lines.append(f'        latin = {latin_flag},')
    lines.append('    )')
    lines.append('')

out.parent.mkdir(parents=True, exist_ok=True)
out.write_text('\n'.join(lines).rstrip() + '\n')
print(f'wrote {out.relative_to(repo)}')
