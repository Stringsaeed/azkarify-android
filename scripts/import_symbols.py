"""Convert Material Symbols Rounded (weight 400) SVGs into VectorDrawables.

Usage: npm pack @material-symbols/svg-400 && tar xzf material-symbols-svg-400-*.tgz
       python3 scripts/import_symbols.py package/rounded

Only the symbols listed below are imported, as res/drawable/sym_<name>.xml.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'app/src/main/res/drawable'

SYMBOLS = [
    # Tabs (outlined when idle, filled when selected).
    'routine', 'routine-fill', 'menu_book', 'menu_book-fill', 'adjust', 'adjust-fill',
    'settings', 'settings-fill',
    # Categories (design README, Iconography).
    'wb_twilight', 'apparel', 'door_open', 'water_drop', 'home', 'mosque', 'campaign',
    'volunteer_activism', 'bedtime', 'cloud', 'family_restroom', 'medical_services', 'spa',
    'air', 'thunderstorm', 'rainy', 'restaurant', 'sick', 'favorite', 'luggage', 'deployed_code',
    # Interface.
    'star', 'star-fill', 'location_on', 'my_location', 'schedule', 'check', 'search', 'more_vert',
    'arrow_back', 'arrow_forward', 'chevron_right', 'format_size', 'fullscreen', 'close', 'add',
    'remove', 'keyboard_arrow_down', 'notifications', 'language', 'palette', 'dark_mode',
    'light_mode', 'info', 'restart_alt', 'shield', 'policy', 'wb_sunny', 'door_front',
]
# Directional symbols flip in right-to-left layouts.
MIRRORED = {'arrow_back', 'arrow_forward', 'chevron_right'}

TEMPLATE = '''<?xml version="1.0" encoding="utf-8"?>
<!-- Material Symbols Rounded, weight 400 (Apache 2.0). Generated by scripts/import_symbols.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="960"
    android:viewportHeight="960"{mirror}>
    <group android:translateY="960">
{paths}
    </group>
</vector>
'''


def main(source: Path):
    for name in SYMBOLS:
        svg = (source / f'{name}.svg').read_text()
        paths = re.findall(r'<path d="([^"]+)"', svg)
        if not paths:
            raise SystemExit(f'{name}: no path')
        body = '\n'.join(
            f'        <path android:fillColor="#FF000000" android:pathData="{d}" />' for d in paths
        )
        base = name.removesuffix('-fill')
        mirror = '\n    android:autoMirrored="true"' if base in MIRRORED else ''
        out = OUT / f"sym_{name.replace('-', '_')}.xml"
        out.write_text(TEMPLATE.format(paths=body, mirror=mirror))
    print(f'{len(SYMBOLS)} symbols written to {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main(Path(sys.argv[1]))
